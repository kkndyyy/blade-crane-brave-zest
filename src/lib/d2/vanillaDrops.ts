const QUALITY_COLS = ["Unique", "Set", "Rare", "Magic"] as const;

export function applyVanillaItemRatio(table: TsvTable) {
  for (const row of table.rows) {
    if (!isDataRow(row)) continue;
    const ver = getCell(row, table, "Version");
    const uber = getCell(row, table, "Uber");
    const cls = getCell(row, table, "Class Specific");
    const spec = VANILLA_ITEMRATIO.find((r) => r.Version === ver && r.Uber === uber && r["Class Specific"] === cls);
    if (!spec) continue;
    for (const [col, val] of Object.entries(spec)) {
      if (col === "Version" || col === "Uber" || col === "Class Specific") continue;
      setCell(row, table, col, val);
    }
  }
}

export function applyVanillaTcQuality(table: TsvTable) {
  for (const row of table.rows) {
    if (!isDataRow(row)) continue;
    const name = getCell(row, table, "Treasure Class");
    const q = VANILLA_TC_QUALITY[name];
    const vals = q ?? ["", "", "", ""];
    QUALITY_COLS.forEach((col, i) => setCell(row, table, col, vals[i]!));
  }
}
