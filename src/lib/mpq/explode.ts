function genDecodeTabs(positions: Uint8Array, startIndexes: Uint8Array, lengthBits: Uint8Array, elements: number) {
  for (let i = 0; i < elements; i++) {
    const length = 1 << lengthBits[i]!;
    for (let index = startIndexes[i]!; index < 0x100; index += length) {
      positions[index] = i;
    }
  }
}

export function explodePkware(input: Uint8Array): Uint8Array {
  if (input.length <= 4) throw new Error("PKWARE 데이터가 너무 짧습니다");
  const ctype = input[0]!;
  const dsizeBits = input[1]!;
  if (dsizeBits < 4 || dsizeBits > 6) throw new Error("PKWARE 사전 크기가 올바르지 않습니다");
  if (ctype !== 0 && ctype !== 1) throw new Error("PKWARE 압축 형식이 올바르지 않습니다");

  const dsizeMask = 0xffff >>> (0x10 - dsizeBits);
  const inBuff = new Uint8Array(0x800);
  let inPos = 3;
  let inBytes = Math.min(input.length, 0x800);
  inBuff.set(input.subarray(0, inBytes));
  let bitBuff = inBuff[2]!;
  let extraBits = 0;
  let srcOff = inBytes;

  const outBuff = new Uint8Array(0x2204);
  const output: number[] = [];
  let outputPos = 0x1000;

  const lengthCodes = new Uint8Array(0x100);
  const distPosCodes = new Uint8Array(0x100);
  const lenBits = LEN_BITS.slice();
  const exLenBits = EX_LEN_BITS.slice();
  const lenBase = LEN_BASE.slice();
  const distBits = DIST_BITS.slice();
  const chBitsAsc = CH_BITS_ASC.slice();
  const offs2C34 = new Uint8Array(0x100);
  const offs2D34 = new Uint8Array(0x100);
  const offs2E34 = new Uint8Array(0x80);
  const offs2EB4 = new Uint8Array(0x100);

  genDecodeTabs(lengthCodes, LEN_CODE, LEN_BITS, LEN_BITS.length);
  genDecodeTabs(distPosCodes, DIST_CODE, DIST_BITS, DIST_BITS.length);

  if (ctype === 1) {
    for (let count = 0xff; count >= 0; count--) {
      const pChCodeAsc = CH_CODE_ASC[count]!;
      let bitsAsc = chBitsAsc[count]!;
      if (bitsAsc <= 8) {
        const add = 1 << bitsAsc;
        for (let acc = pChCodeAsc; acc < 0x100; acc += add) offs2C34[acc] = count;
      } else if ((pChCodeAsc & 0xff) !== 0) {
        offs2C34[pChCodeAsc & 0xff] = 0xff;
        if (pChCodeAsc & 0x3f) {
          bitsAsc -= 4;
          chBitsAsc[count] = bitsAsc;
          const add = 1 << bitsAsc;
          for (let acc = pChCodeAsc >>> 4; acc < 0x100; acc += add) offs2D34[acc] = count;
        } else {
          bitsAsc -= 6;
          chBitsAsc[count] = bitsAsc;
          const add = 1 << bitsAsc;
          for (let acc = pChCodeAsc >>> 6; acc < 0x80; acc += add) offs2E34[acc] = count;
        }
      } else {
        bitsAsc -= 8;
        chBitsAsc[count] = bitsAsc;
        const add = 1 << bitsAsc;
        for (let acc = pChCodeAsc >>> 8; acc < 0x100; acc += add) offs2EB4[acc] = count;
      }
    }
  }

  const refill = (): boolean => {
    if (inPos === inBytes) {
      const n = Math.min(0x800, input.length - srcOff);
      if (n === 0) return false;
      inBuff.set(input.subarray(srcOff, srcOff + n));
      inBytes = n;
      inPos = 0;
      srcOff += n;
    }
    return true;
  };

  const wasteBits = (nBits: number): boolean => {
    if (nBits <= extraBits) {
      extraBits -= nBits;
      bitBuff >>>= nBits;
      return true;
    }
    bitBuff >>>= extraBits;
    if (!refill()) return false;
    bitBuff |= inBuff[inPos++]! << 8;
    bitBuff >>>= nBits - extraBits;
    extraBits = extraBits - nBits + 8;
    return true;
  };

  const decodeLit = (): number => {
    if (bitBuff & 1) {
      if (!wasteBits(1)) return 0x306;
      const lengthCode0 = lengthCodes[bitBuff & 0xff]!;
      if (!wasteBits(lenBits[lengthCode0]!)) return 0x306;
      let lengthCode = lengthCode0;
      const extraLengthBits = exLenBits[lengthCode]!;
      if (extraLengthBits) {
        const extraLength = bitBuff & ((1 << extraLengthBits) - 1);
        if (!wasteBits(extraLengthBits)) {
          if (lengthCode + extraLength !== 0x10e) return 0x306;
        }
        lengthCode = lenBase[lengthCode]! + extraLength;
      }
      return lengthCode + 0x100;
    }
    if (!wasteBits(1)) return 0x306;
    if (ctype === 0) {
      const uncompressedByte = bitBuff & 0xff;
      if (!wasteBits(8)) return 0x306;
      return uncompressedByte;
    }
    let value: number;
    if (bitBuff & 0xff) {
      value = offs2C34[bitBuff & 0xff]!;
      if (value === 0xff) {
        if (bitBuff & 0x3f) {
          if (!wasteBits(4)) return 0x306;
          value = offs2D34[bitBuff & 0xff]!;
        } else {
          if (!wasteBits(6)) return 0x306;
          value = offs2E34[bitBuff & 0x7f]!;
        }
      }
    } else {
      if (!wasteBits(8)) return 0x306;
      value = offs2EB4[bitBuff & 0xff]!;
    }
    return wasteBits(chBitsAsc[value]!) ? value : 0x306;
  };

  const decodeDist = (repLength: number): number => {
    const distPosCode = distPosCodes[bitBuff & 0xff]!;
    const distPosBits = distBits[distPosCode]!;
    if (!wasteBits(distPosBits)) return 0;
    let distance: number;
    if (repLength === 2) {
      distance = (distPosCode << 2) | (bitBuff & 0x03);
      if (!wasteBits(2)) return 0;
    } else {
      distance = (distPosCode << dsizeBits) | (bitBuff & dsizeMask);
      if (!wasteBits(dsizeBits)) return 0;
    }
    return distance + 1;
  };

  const flush = (from: number, count: number) => {
    for (let i = 0; i < count; i++) output.push(outBuff[from + i]!);
  };

  let nextLiteral = decodeLit();
  while (nextLiteral < 0x305) {
    if (nextLiteral >= 0x100) {
      let repLength = nextLiteral - 0xfe;
      const minusDist = decodeDist(repLength);
      if (minusDist === 0) break;
      let target = outputPos;
      let source = target - minusDist;
      outputPos += repLength;
      while (repLength-- > 0) outBuff[target++] = outBuff[source++]!;
    } else {
      outBuff[outputPos++] = nextLiteral;
    }
    if (outputPos >= 0x2000) {
      flush(0x1000, 0x1000);
      outBuff.copyWithin(0, 0x1000, outputPos);
      outputPos -= 0x1000;
    }
    nextLiteral = decodeLit();
  }
  flush(0x1000, outputPos - 0x1000);
  return Uint8Array.from(output);
}
